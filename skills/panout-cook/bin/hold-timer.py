class Audio:
    """Asynchronous audio: announcements queue, ticks and nags never block."""

    def __init__(self, mode):
        self.mode = mode
        self.chime = SCRIPT_DIR / "chime.sh"
        self.speak = SCRIPT_DIR / "speak.sh"
        self.failure = None  # first hard failure, for the agent's benefit
        self.failure_reported = False
        self._child = None
        self._child_started = 0.0
        self._child_kind = None
        self._dying = []  # [(Popen, monotonic instant SIGTERM was sent)]
        self._queue = []  # [(argv, kind)] announcements waiting their turn

    # -- state ---------------------------------------------------------------

    def required_scripts(self):
        if self.mode == "silent":
            return ()
        if self.mode == "chime":
            return (self.chime,)
        return (self.chime, self.speak)

    def preflight(self):
        """Describe why audio cannot work at all, or None if it can."""
        missing = [str(p) for p in self.required_scripts() if not os.access(p, os.X_OK)]
        if not missing:
            return None
        self.failure = "missing or not executable: " + ", ".join(missing)
        return self.failure

    def busy(self):
        if self._child is None:
            return False
        code = self._child.poll()
        if code is not None:
            # Only sounds that ended on their own land here; ones we killed are
            # in _dying, so a non-zero code always means the script itself
            # failed and the cook heard nothing.
            if code != 0:
                self.note_failure(f"audio script exited {code}")
            self._child = None
            self._child_kind = None
            return False
        return True

    def note_failure(self, description):
        """Record a failure for the agent. Every occurrence hits stderr; only
        the first is worth an stdout event."""
        log(f"audio failed: {description}")
        if self.failure is None:
            self.failure = description

    def sounding(self):
        """True while anything is playing or waiting to play."""
        return bool(self._queue) or self.busy()

    # -- requests ------------------------------------------------------------

    def announce(self, message):
        """Queue an event announcement. Cuts off a tick, never other speech."""
        if self.mode == "silent":
            return
        if self.mode == "chime":
            argv = [str(self.chime), "alert"]
        else:
            argv = [str(self.speak), message]
        self._queue.append((argv, "event"))
        while len(self._queue) > MAX_QUEUED_ANNOUNCEMENTS:
            self._queue.pop(0)
            log("audio running behind — dropped a stale queued announcement")
        if self._child_kind == "tick":
            self._terminate_current()

    def tick(self):
        """Heartbeat. Only meaningful now, so drop it if audio is occupied."""
        if self.mode == "silent" or self.sounding():
            return
        self._start([str(self.chime), "tick"], "tick")

    def nag(self, message):
        """Completion alarm. Returns played | silent | suppressed | failed."""
        if self.mode == "silent":
            return "silent"
        if self.sounding():
            return "suppressed"
        if self.mode == "chime":
            argv = [str(self.chime), "alarm"]
        else:
            # Alarm then speech, sequenced by a shell so the loop keeps running.
            # Paths and message travel as positional args — no quoting hazards.
            argv = [
                "/bin/sh",
                "-c",
                '"$1" alarm; "$2" "$3"',
                "hold-timer-nag",
                str(self.chime),
                str(self.speak),
                message,
            ]
        return "played" if self._start(argv, "nag") else "failed"

    # -- lifecycle -----------------------------------------------------------

    def pump(self):
        """Reap finished sounds, kill wedged ones, start whatever is queued."""
        now = time.monotonic()

        still_dying = []
        for child, killed_at in self._dying:
            if child.poll() is not None:
                continue
            if now - killed_at > KILL_GRACE_SECONDS:
                self._signal(child, signal.SIGKILL)
            still_dying.append((child, killed_at))
        self._dying = still_dying

        if self.busy() and now - self._child_started > STUCK_AUDIO_SECONDS:
            self.note_failure(
                f"wedged for {fmt_duration(now - self._child_started)} — killed so it "
                "cannot mute the alarm"
            )
            self._terminate_current()

        if self._queue and not self.busy():
            argv, kind = self._queue.pop(0)
            self._start(argv, kind)

    def stop(self):
        """Silence current and queued audio. Does not block the caller."""
        self._queue.clear()
        self._terminate_current()

    def shutdown(self):
        """Silence everything, and make sure nothing is left sounding."""
        self.stop()
        deadline = time.monotonic() + 3.0
        while self._dying and time.monotonic() < deadline:
            self.pump()
            if self._dying:
                time.sleep(0.05)
        for child, _ in self._dying:
            if child.poll() is None:
                self._signal(child, signal.SIGKILL)
                try:
                    child.wait(timeout=1)
                except subprocess.TimeoutExpired:
                    log("an audio process outlived SIGKILL")
        self._dying = []

    # -- internals -----------------------------------------------------------

    def _start(self, argv, kind):
        for path in self.required_scripts():
            if not os.access(path, os.X_OK):
                # Already stated once at startup; don't narrate it every tick.
                if self.failure is None:
                    self.note_failure(f"missing or not executable: {path}")
                return False
        try:
            # Own session so the whole sound pipeline dies with one killpg.
            self._child = subprocess.Popen(
                argv,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                start_new_session=True,
            )
        except OSError as exc:
            self.note_failure(f"cannot run audio: {exc}")
            return False
        self._child_started = time.monotonic()
        self._child_kind = kind
        return True

    def _terminate_current(self):
        child, self._child = self._child, None
        self._child_kind = None
        if child is None or child.poll() is not None:
            return
        self._signal(child, signal.SIGTERM)
        self._dying.append((child, time.monotonic()))

    @staticmethod
    def _signal(child, sig):
        try:
            os.killpg(os.getpgid(child.pid), sig)
        except OSError:
            try:
                child.send_signal(sig)
            except OSError:
                pass


# ---------------------------------------------------------------------------
# Timing loop
# ---------------------------------------------------------------------------

def fire(event, wall):
    payload = dict(event.payload)
    payload["fired_at"] = int(wall)
    late = wall - event.target
    if late > DRIFT_TOLERANCE:
        payload["late_by"] = int(round(late))
    emit(payload)
    log(f"fired {payload['type']} (target +{event.after:g}s, {late:+.1f}s)")


def report_gap(lost, overdue, wall):
    span = fmt_duration(lost)
    if overdue:
        message = f"Clock gap of {span} — {len(overdue)} event(s) overdue, firing now"
    else:
        message = f"Clock gap of {span} — timer re-anchored, nothing due yet"
    emit(
        {
            "type": "gap",
            "seconds": int(round(lost)),
            "message": message,
            "detail": (
                f"{span} of real time passed without the timer running — the machine "
                "was asleep or suspended, or the wall clock jumped forward. Event "
                "timing stays anchored to the wall clock, so anything overdue fires "
                "now. Recompute remaining hold time from the wall clock before telling "
                "the cook anything."
            ),
            "fired_at": int(wall),
        }
    )
    log(f"clock gap {span} ({len(overdue)} overdue)")


def report_backward_step(skew, pending_count, wall):
    span = fmt_duration(skew)
    emit(
        {
            "type": "gap",
            "seconds": int(round(skew)),
            "message": (
                f"Wall clock stepped back {span} — hold re-anchored, remaining time "
                "unchanged"
            ),
            "detail": (
                f"The system clock moved backwards by {span} (an NTP correction or a "
                "manual change). Remaining event times moved with it, so the hold is "
                "not silently extended by that much. Trust remaining-time figures from "
                "here on, not any absolute clock time you announced earlier."
            ),
            "fired_at": int(wall),
        }
    )
    log(f"wall clock stepped back {span} — re-anchored {pending_count} pending event(s)")


def run(events, audio, tick_seconds, nag_seconds):
    """Fire events on schedule, then nag until killed (or exit if nag is off)."""
    start_wall = time.time()
    start_mono = time.monotonic()
    for event in events:
        event.target = start_wall + event.after

    pending = list(events)
    next_tick = start_mono + tick_seconds if tick_seconds > 0 else None
    nag_deadline = None
    nag_count = 0
    drain_deadline = None
    nag_message = events[-1].payload["speak"]
    prev_wall, prev_mono = start_wall, start_mono
    intended_wake = None

    log(
        f"armed: {len(events)} event(s), last at +{events[-1].after:g}s, "
        f"audio {audio.mode}, tick {tick_seconds:g}s, nag {nag_seconds:g}s"
    )

    while True:
        wall = time.time()
        mono = time.monotonic()

        # Lost time, from whichever clock reveals it: a sleep that overran its
        # monotonic deadline (frozen or starved process), or wall time running
        # ahead of monotonic (suspend, or a forward clock step). Time spent
        # working inside a pass is excluded — see intended_wake below.
        overslept = 0.0 if intended_wake is None else mono - intended_wake
        skew = (wall - prev_wall) - (mono - prev_mono)
        prev_wall, prev_mono = wall, mono

        if skew < -DRIFT_TOLERANCE:
            # Clock went backwards: keep remaining time honest instead of
            # silently holding for the difference.
            for event in pending:
                event.target += skew
            report_backward_step(skew, len(pending), wall)

        lost = max(overslept, skew)
        overdue = [e for e in pending if e.target <= wall]
        if lost > GAP_SECONDS or (lost > DRIFT_TOLERANCE and overdue):
            report_gap(lost, overdue, wall)

        fired = []
        while pending and pending[0].target <= wall:
            event = pending.pop(0)
            fire(event, wall)
            fired.append(event)

        if fired:
            if len(fired) == 1:
                audio.announce(fired[0].payload["speak"])
            else:
                # A burst means the cook missed things. One announcement that
                # says so beats several talking over each other.
                audio.announce(
                    f"{len(fired)} timer alerts came due at once. "
                    f"{fired[-1].payload['speak']}"
                )
            if not pending:
                next_tick = None
                if nag_seconds > 0:
                    nag_deadline = mono + nag_seconds
                else:
                    drain_deadline = mono + DRAIN_SECONDS

        if next_tick is not None and mono >= next_tick:
            if not fired:
                audio.tick()
            while next_tick <= mono:
                next_tick += tick_seconds

        if nag_deadline is not None and mono >= nag_deadline:
            nag_count += 1
            status = audio.nag(nag_message)
            if status == "played":
                log(f"nag #{nag_count} — alarm sounding, TaskStop to silence")
            elif status == "silent":
                log(f"nag #{nag_count} — silent mode, no alarm; waiting for TaskStop")
            elif status == "suppressed":
                log(f"nag #{nag_count} — audio still busy, alarm skipped this round")
            else:
                log(f"nag #{nag_count} — alarm could not play")
            nag_deadline = mono + nag_seconds

        audio.pump()

        if audio.failure is not None and not audio.failure_reported:
            audio.failure_reported = True
            emit_error(
                f"Timer audio unavailable: {audio.failure}",
                (
                    "The hold timer is still counting and will keep sending events, but "
                    "the cook will hear nothing from it — no ticks, no spoken "
                    "announcements, no completion alarm. Tell them, and treat every "
                    "event as something you have to voice yourself."
                ),
                fatal=False,
            )

        if drain_deadline is not None and (
            not audio.sounding() or mono >= drain_deadline
        ):
            log("last event fired and nagging is disabled — exiting")
            return EXIT_OK

        # Sleep on the monotonic clock, and remember when the sleep was meant to
        # end. Measuring from here means a slow pass costs no false gap.
        sleep_start = time.monotonic()
        intended = max(0.0, (mono + LOOP_SECONDS) - sleep_start)
        intended_wake = sleep_start + intended
        if intended > 0:
            time.sleep(intended)


