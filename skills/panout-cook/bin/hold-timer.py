#!/usr/bin/env python3
"""hold-timer.py — passive-phase hold timer for the Pan Out cook skill.

Runs under the Claude Code Monitor tool. Every line this script writes to
stdout wakes the cook agent, so stdout stays sparse: one compact JSON object
per timer event and nothing else. Diagnostics go to stderr, which Monitor
collects without waking anyone. The script also owns the kitchen audio channel
-- heartbeat tick, spoken announcements, completion alarm -- so the cook hears
what is happening whether or not the agent is awake.

Usage
-----
    python3 hold-timer.py '<schedule-json>' [options]
    python3 hold-timer.py /path/to/schedule.json [options]

The positional argument is the schedule JSON itself, or a path to a file
holding it.

Options
-------
    --label TEXT       Name of the hold; used in stderr logs. Default "hold".
    --tick-seconds N   Heartbeat tick every N seconds. Default 60, 0 = off.
    --nag-seconds N    Completion alarm interval. Default 45, 0 = off.
    --audio-mode MODE  tts (speech + chimes) | chime (chimes only) | silent.

Schedule
--------
`after` is seconds from process start. The agent does the wall-clock math; the
script only counts forward from the moment it was armed.

    {"version": 1, "events": [
      {"after": 600,
       "type": "progress",
       "message": "10 min elapsed - bath holding",
       "detail": "Phase 2 progress check. 80 min remain. Check the bag seal.",
       "speak": "Ten minutes down, eighty to go."}
    ]}

`after`, `type`, and `message` are required. `detail` and `speak` are optional;
`speak` defaults to `message`. Event types are opaque to this script -- use
whatever vocabulary the skill needs (progress, preflight, ready-check,
countdown, complete). Events fire in `after` order regardless of input order.
Write `detail` as if the reader has no session memory: the agent woken 90
minutes from now may have lost its context to compression.

Stdout events
-------------
One flushed JSON object per line -- the event as supplied, plus `fired_at`
(unix epoch) and, when it fired more than 2s late, `late_by` (seconds).

Two event types are generated by the script itself:

    {"type": "gap",   "seconds": 612, ...}  wall clock jumped (machine slept);
                                            overdue events follow immediately,
                                            in order, none skipped
    {"type": "error", "message": ...}       unusable schedule; exit 1 follows

Audio
-----
Sound comes from `chime.sh` and `speak.sh` next to this script, spawned
asynchronously so audio latency never delays timing. One sound at a time: an
event announcement interrupts a tick, and a tick is dropped rather than layered
over speech.

    heartbeat tick    chime.sh tick             (tts and chime modes)
    event             speak.sh <speak>          (tts) / chime.sh alert (chime)
    completion nag    chime.sh alarm + speech   (tts) / chime.sh alarm (chime)

Ticks stop once the last event has fired -- the nag takes over from there.

Lifecycle
---------
The script never exits on its own. After the last event it goes stdout-quiet
and nags -- alarm plus speech every `--nag-seconds` -- until it is killed. That
is the acknowledgement channel: the cook hears the alarm, tells the agent, and
the agent calls TaskStop on the Monitor task. Extending a hold is the same
move -- TaskStop, then re-arm with a fresh schedule whose `after` values are
shifted by the extension. SIGTERM and SIGINT cut the audio and exit 0 with no
farewell noise.

Exit codes: 0 on signal, 1 on unusable schedule. Python 3 stdlib only.
"""

import argparse
import json
import os
import signal
import subprocess
import sys
import time
from pathlib import Path

LOOP_SECONDS = 1.0
# An unexplained wall-clock jump this large means the machine was suspended.
GAP_SECONDS = 15.0
# Ordinary scheduler jitter. Drift under this is not worth reporting.
DRIFT_TOLERANCE = 2.0

SCRIPT_DIR = Path(__file__).resolve().parent
AUDIO_MODES = ("tts", "chime", "silent")

_LABEL = "hold"

# Cook messages carry degree signs and em-dashes; keep them literal where the
# stream can take it rather than shipping \u escapes to the agent.
for _stream in (sys.stdout, sys.stderr):
    if hasattr(_stream, "reconfigure"):
        try:
            _stream.reconfigure(encoding="utf-8", errors="backslashreplace")
        except (OSError, ValueError):
            pass


class ScheduleError(ValueError):
    """The schedule was missing, malformed, or empty."""


class Shutdown(Exception):
    """SIGTERM/SIGINT — the cook acknowledged, or the agent is re-arming."""


def log(message):
    print(f"hold-timer[{_LABEL}]: {message}", file=sys.stderr, flush=True)


def emit(obj):
    """Write one flushed JSON line to stdout. Each line wakes the agent."""
    print(json.dumps(obj, separators=(",", ":"), ensure_ascii=False), flush=True)


def fmt_duration(seconds):
    seconds = int(round(seconds))
    if seconds < 60:
        return f"{seconds}s"
    minutes, rest = divmod(seconds, 60)
    return f"{minutes} min" if rest == 0 else f"{minutes} min {rest}s"


# ---------------------------------------------------------------------------
# Schedule
# ---------------------------------------------------------------------------

class Event:
    __slots__ = ("payload", "after", "target")

    def __init__(self, payload, after):
        self.payload = payload
        self.after = after
        self.target = 0.0


def parse_schedule(raw):
    """Parse schedule JSON (literal or file path) into Events sorted by time."""
    text = raw.strip()
    if not text:
        raise ScheduleError("schedule argument is empty")

    if text[0] not in "{[":
        try:
            text = Path(text).read_text(encoding="utf-8").strip()
        except OSError as exc:
            raise ScheduleError(f"cannot read schedule file '{raw}': {exc}")
        if not text:
            raise ScheduleError(f"schedule file '{raw}' is empty")

    try:
        data = json.loads(text)
    except json.JSONDecodeError as exc:
        raise ScheduleError(f"schedule is not valid JSON: {exc}")

    if not isinstance(data, dict):
        raise ScheduleError("schedule must be a JSON object")
    if data.get("version") != 1:
        raise ScheduleError(
            f"unsupported schedule version {data.get('version')!r} (expected 1)"
        )

    raw_events = data.get("events")
    if not isinstance(raw_events, list) or not raw_events:
        raise ScheduleError("schedule has no events")

    events = []
    for index, item in enumerate(raw_events):
        events.append(parse_event(index, item))
    events.sort(key=lambda e: e.after)
    return events


def parse_event(index, item):
    if not isinstance(item, dict):
        raise ScheduleError(f"event {index} is not a JSON object")

    after = item.get("after")
    if isinstance(after, bool) or not isinstance(after, (int, float)):
        raise ScheduleError(
            f"event {index} needs a numeric 'after' (seconds from start)"
        )
    if after < 0:
        raise ScheduleError(f"event {index} has a negative 'after': {after}")

    payload = dict(item)
    for field in ("type", "message"):
        value = payload.get(field)
        if not isinstance(value, str) or not value.strip():
            raise ScheduleError(f"event {index} needs a non-empty '{field}'")

    for field in ("detail", "speak"):
        if field in payload and not isinstance(payload[field], str):
            raise ScheduleError(f"event {index} has a non-string '{field}'")

    payload.setdefault("speak", payload["message"])
    return Event(payload, float(after))


# ---------------------------------------------------------------------------
# Audio
# ---------------------------------------------------------------------------

class Audio:
    """Fire-and-forget audio, one sound at a time, never blocking the loop."""

    def __init__(self, mode):
        self.mode = mode
        self.chime = SCRIPT_DIR / "chime.sh"
        self.speak = SCRIPT_DIR / "speak.sh"
        self._child = None
        self._missing = set()

    def busy(self):
        return self._child is not None and self._child.poll() is None

    def tick(self):
        if self.mode == "silent" or self.busy():
            return
        self._spawn([str(self.chime), "tick"], (self.chime,))

    def announce(self, payload):
        if self.mode == "silent":
            return
        if self.mode == "chime":
            self._spawn([str(self.chime), "alert"], (self.chime,))
        else:
            self._spawn([str(self.speak), payload["speak"]], (self.speak,))

    def nag(self, message):
        """Alarm (plus speech in tts mode). Skipped while audio is playing."""
        if self.mode == "silent" or self.busy():
            return
        if self.mode == "chime":
            self._spawn([str(self.chime), "alarm"], (self.chime,))
            return
        # Alarm then speech, sequenced by a shell so the loop keeps running.
        # Paths and message travel as positional args — no quoting hazards.
        self._spawn(
            [
                "/bin/sh",
                "-c",
                '"$1" alarm; "$2" "$3"',
                "hold-timer-nag",
                str(self.chime),
                str(self.speak),
                message,
            ],
            (self.chime, self.speak),
        )

    def stop(self):
        """Silence any in-flight sound. Safe to call repeatedly."""
        child, self._child = self._child, None
        if child is None or child.poll() is not None:
            return
        try:
            os.killpg(os.getpgid(child.pid), signal.SIGTERM)
        except OSError:
            pass
        try:
            child.wait(timeout=2)
        except subprocess.TimeoutExpired:
            log("audio process did not exit after SIGTERM")

    def _spawn(self, argv, required):
        for path in required:
            if not os.access(path, os.X_OK):
                if path not in self._missing:
                    self._missing.add(path)
                    log(f"audio unavailable: {path} is missing or not executable")
                return
        self.stop()
        try:
            # Own session so stop() can kill the whole sound pipeline at once.
            self._child = subprocess.Popen(
                argv,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                start_new_session=True,
            )
        except OSError as exc:
            log(f"audio failed: {exc}")


# ---------------------------------------------------------------------------
# Timing loop
# ---------------------------------------------------------------------------

def fire(event, now, audio):
    payload = dict(event.payload)
    payload["fired_at"] = int(now)
    late = now - event.target
    if late > DRIFT_TOLERANCE:
        payload["late_by"] = int(round(late))
    emit(payload)
    audio.announce(payload)
    log(f"fired {payload['type']} (target +{event.after:g}s, {late:+.1f}s)")


def report_gap(drift, overdue, now):
    span = fmt_duration(drift)
    if overdue:
        message = f"Clock gap of {span} — {len(overdue)} event(s) overdue, firing now"
    else:
        message = f"Clock gap of {span} — timer re-anchored, nothing missed yet"
    emit(
        {
            "type": "gap",
            "seconds": int(round(drift)),
            "message": message,
            "detail": (
                f"The wall clock jumped {span} past the expected tick — the machine "
                "was asleep or suspended. Timing is re-anchored to the wall clock. "
                "Any event lines that follow are late by roughly this much; "
                "recompute remaining hold time before telling the cook anything."
            ),
            "fired_at": int(now),
        }
    )
    log(f"clock gap {span} ({len(overdue)} overdue)")


def run(events, audio, tick_seconds, nag_seconds):
    """Fire events on schedule, then nag until killed. Never returns."""
    start = time.time()
    for event in events:
        event.target = start + event.after

    pending = list(events)
    next_tick = start + tick_seconds if tick_seconds > 0 else None
    expected_wake = None
    nag_deadline = None
    nag_count = 0
    nag_message = events[-1].payload["speak"]

    log(
        f"armed: {len(events)} event(s), last at +{events[-1].after:g}s, "
        f"audio {audio.mode}, tick {tick_seconds:g}s, nag {nag_seconds:g}s"
    )

    while True:
        now = time.time()

        # Wall-clock anchoring: a suspend shows up as drift past expected_wake.
        if expected_wake is not None:
            drift = now - expected_wake
            overdue = [e for e in pending if e.target <= now - DRIFT_TOLERANCE]
            if drift > GAP_SECONDS or (drift > DRIFT_TOLERANCE and overdue):
                report_gap(drift, overdue, now)

        fired_any = False
        while pending and pending[0].target <= now:
            fire(pending.pop(0), now, audio)
            fired_any = True
            if not pending:
                next_tick = None
                nag_deadline = now + nag_seconds if nag_seconds > 0 else None

        if next_tick is not None and now >= next_tick:
            if not fired_any:
                audio.tick()
            while next_tick <= now:
                next_tick += tick_seconds

        if nag_deadline is not None and now >= nag_deadline:
            nag_count += 1
            log(f"nag #{nag_count} — unacknowledged, TaskStop to silence")
            audio.nag(nag_message)
            nag_deadline = now + nag_seconds

        expected_wake = now + LOOP_SECONDS
        remaining = expected_wake - time.time()
        if remaining > 0:
            time.sleep(remaining)


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

def _shutdown_handler(signum, _frame):
    raise Shutdown(signum)


def parse_args(argv):
    parser = argparse.ArgumentParser(
        prog="hold-timer.py",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "schedule", help="schedule JSON, or a path to a file holding it"
    )
    parser.add_argument(
        "--label", default="hold", help="name of the hold, used in stderr logs"
    )
    parser.add_argument(
        "--tick-seconds",
        type=float,
        default=60.0,
        metavar="N",
        help="heartbeat tick interval, 0 to disable (default: 60)",
    )
    parser.add_argument(
        "--nag-seconds",
        type=float,
        default=45.0,
        metavar="N",
        help="completion alarm interval, 0 to disable (default: 45)",
    )
    parser.add_argument(
        "--audio-mode",
        choices=AUDIO_MODES,
        default="tts",
        help="how to make noise (default: tts)",
    )
    args = parser.parse_args(argv)
    if args.tick_seconds < 0 or args.nag_seconds < 0:
        parser.error("--tick-seconds and --nag-seconds cannot be negative")
    return args


def main(argv=None):
    global _LABEL
    args = parse_args(argv)
    _LABEL = args.label

    signal.signal(signal.SIGTERM, _shutdown_handler)
    signal.signal(signal.SIGINT, _shutdown_handler)

    audio = None
    try:
        events = parse_schedule(args.schedule)
        audio = Audio(args.audio_mode)
        run(events, audio, args.tick_seconds, args.nag_seconds)
    except ScheduleError as exc:
        emit(
            {
                "type": "error",
                "message": f"Timer could not start: {exc}",
                "detail": (
                    "hold-timer.py rejected its schedule and exited. No events "
                    "will fire. Tell the cook, then fall back to the manual "
                    "timer mode for the rest of this hold."
                ),
                "fired_at": int(time.time()),
            }
        )
        log(f"error: {exc}")
        return 1
    except Shutdown:
        log("stopped")
        return 0
    except Exception as exc:  # noqa: BLE001 — a crash must still wake the agent
        emit(
            {
                "type": "error",
                "message": f"Timer crashed: {exc}",
                "detail": (
                    "hold-timer.py died mid-hold, so no further events will "
                    "fire. Tell the cook, work out how much hold time is left "
                    "from the state file, and fall back to the manual timer."
                ),
                "fired_at": int(time.time()),
            }
        )
        log(f"crashed: {exc!r}")
        return 1
    finally:
        if audio is not None:
            audio.stop()


if __name__ == "__main__":
    sys.exit(main())
