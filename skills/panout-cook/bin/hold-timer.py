#!/usr/bin/env python3
"""hold-timer.py — passive-phase hold timer for the Pan Out cook skill.

Runs under the Claude Code Monitor tool. Every line this script writes to
stdout wakes the cook agent, so stdout stays sparse: one compact JSON object
per timer event and nothing else. Diagnostics go to stderr, which Monitor
collects without waking anyone. The script also owns the kitchen audio channel
-- heartbeat tick, spoken announcements, completion alarm -- so the cook hears
what is happening whether or not the agent is awake.

Usage
-----
    python3 hold-timer.py /path/to/schedule.json [options]
    python3 hold-timer.py '<schedule-json>' [options]

The positional argument is a path to a file holding the schedule, or the
schedule JSON itself. **Prefer the file form.** Cook prose is full of
apostrophes ("Don't lift the lid"), and an inline JSON argument has to survive
shell quoting to get here at all — a quoting failure kills the command before
this script exists to report anything.

Options
-------
    --label TEXT       Name of the hold; used in stderr logs. Default "hold".
    --tick-seconds N   Heartbeat tick every N seconds. Default 60. 0 disables;
                       otherwise 1 or more.
    --nag-seconds N    Completion alarm interval. Default 45. 0 disables it,
                       and the script then exits after the last event;
                       otherwise 1 or more.
    --audio-mode MODE  tts (speech + chimes) | chime (chimes only) | silent.

Schedule
--------
`after` is seconds from process start. The agent does the wall-clock math; the
script only counts forward from the moment it was armed.

    {"version": 1, "events": [
      {"after": 600,
       "type": "progress",
       "message": "10 min elapsed — bath holding",
       "detail": "Phase 2 progress check. 80 min remain. Check the bag seal.",
       "speak": "Ten minutes down, eighty to go."}
    ]}

Top level: `version` must be the integer 1. It is required, and it is validated
before any event, so a schedule that omits it fires nothing and reports only the
version problem. Per event, `after` (finite, >= 0), `type`, and `message` are
required. `detail` and `speak` are optional and must be non-empty when present;
`speak` defaults to `message`. No string may exceed 4096 characters — each one
ends up on a stdout line that lands in the agent's context, so a runaway
`detail` would flood exactly the thing it was written to protect. Event types
are opaque to this script — use whatever vocabulary the
skill needs (progress, preflight, ready-check, countdown, complete) — except
`gap` and `error`, which the timer emits itself and a schedule may not claim.
`fired_at` and `late_by` belong to the timer; a schedule supplying them has
them dropped. Events fire in `after` order regardless of input order. Write
`detail` as if the reader has no session memory: the agent woken 90 minutes
from now may have lost its context to compression.

Stdout events
-------------
One flushed JSON object per line — the event as supplied, plus `fired_at` (unix
epoch) and, when it fired more than 2s late, `late_by` (seconds). Two things to
expect when diffing a line against what you wrote: `speak` is always present
(materialized from `message` when it was defaulted), and any key this script
does not know about is passed through untouched.

Two event types are generated by the script itself:

    {"type": "gap", "seconds": 612, ...}
        Real time passed with the timer not running (machine asleep, or the
        clock jumped). Overdue events follow immediately, in order, none
        skipped. `seconds` is negative when the wall clock stepped backwards
        and the hold was re-anchored to keep remaining time honest.

    {"type": "error", "message": ..., "fatal": true|false}
        fatal true: the timer is dead and a non-zero exit follows — fall back
        to a manual timer. fatal false: the timer is still counting, but
        something is degraded, such as audio the cook will never hear.

Clocks
------
Event targets and `fired_at` live on the **wall clock**, because food cooks in
real time — a bath keeps running while the laptop sleeps, so a hold must not
stretch by the length of a suspend. Loop scheduling and the tick and nag
intervals use the **monotonic** clock, so an NTP correction cannot shift them.

Lost time is detected from both clocks: a sleep that overran its monotonic
deadline (the process was frozen or starved), and wall time that advanced
further than monotonic (the machine was suspended, or the clock stepped
forward). Work done inside a loop pass — audio bookkeeping, slow I/O — is
measured out, so a stalled sound can never masquerade as a sleeping laptop. A
suspend and a forward clock step are indistinguishable without
platform-specific clocks, so both are reported as a gap and the agent is told
to recompute from the wall clock. A backward step re-anchors the remaining
events and says so. `gap.seconds` is rounded to whole seconds.

Small losses are absorbed rather than reported: under ~2s, or under 15s with
nothing overdue, there is no `gap` line and no `late_by`. The cost is a bounded
late bias of up to one poll interval (1s) on later events, which does not
accumulate across repeated small freezes and never stretches the hold.

Audio
-----
Sound comes from `chime.sh` and `speak.sh` next to this script, spawned
asynchronously so audio latency never delays timing.

    heartbeat tick    chime.sh tick             (tts and chime modes)
    event             speak.sh <speak>          (tts) / chime.sh alert (chime)
    completion nag    chime.sh alarm + speech   (tts) / chime.sh alarm (chime)

Announcements queue rather than interrupt each other, so nothing is cut off
mid-word; a burst of overdue events after a suspend is announced once, naming
how many came due. An event announcement does cut off a heartbeat tick, and a
tick is dropped rather than layered over speech. Ticks stop once the last event
has fired — the nag takes over. The nag speaks the **last event's `speak` text,
verbatim, every round**, so write that line to survive repetition.

A sound that wedges cannot mute the completion alarm, but it does delay it: a
nag round landing while audio is still busy is skipped, and the wedged sound is
killed at the 10s mark, so the worst-case alarm period becomes roughly 10s plus
the nag interval. At the 45s default nothing is skipped; intervals under ~11s
degrade.

Audio that fails where the cook can tell but the agent cannot — a script that
exits non-zero, or one that had to be killed for wedging — is reported to the
agent once as a `fatal: false` error line, with per-occurrence detail on stderr.
Startup checks only existence and the executable bit, so this is the path that
catches a script which runs and then fails.

Lifecycle
---------
With nagging enabled (the default) the script never exits on its own. After the
last event it goes stdout-quiet and nags — alarm plus speech every
`--nag-seconds` — until it is killed. That is the acknowledgement channel: the
cook hears the alarm, tells the agent, and the agent calls TaskStop on the
Monitor task. Extending a hold is the same move — TaskStop, then re-arm, keeping
the original flags. A re-armed process starts its own clock at zero, so offsets
must be recomputed rather than shifted: `new_after = old_after - elapsed + N`.
Adding N alone fires late by the whole elapsed hold. With `--nag-seconds 0`
there is nothing to acknowledge, so the script exits 0 once the last event's
audio has finished.

Nothing reaches stdout during the nag phase, including gap reporting: once the
last event has fired nothing can be overdue, so a suspend mid-nag is not
reported and nagging simply resumes on cadence.

SIGTERM, SIGINT, and SIGHUP cut the audio and exit 0 with no farewell noise;
further signals during that cleanup are ignored rather than raising through it.
One startup race is unavoidable: a signal arriving in the first ~20ms, before
the interpreter reaches `install_handlers()`, kills the process by default
disposition (exit -15). TaskStop lands minutes after arming, so this is a
theoretical window rather than a practical one.

Exit codes: 0 normal or signalled, 1 unusable schedule, 2 bad command line
(argparse), 3 unexpected crash. Python 3 stdlib only.
"""

import argparse
import json
import math
import os
import signal
import subprocess
import sys
import time
from pathlib import Path

LOOP_SECONDS = 1.0
# Lost time beyond this is worth reporting even when nothing was due.
GAP_SECONDS = 15.0
# Ordinary scheduler jitter. Drift under this is not worth reporting.
DRIFT_TOLERANCE = 2.0
# A sound still running after this long is wedged; kill it rather than let it
# mute everything behind it.
STUCK_AUDIO_SECONDS = 10.0
# Grace between SIGTERM and SIGKILL for a sound being silenced.
KILL_GRACE_SECONDS = 1.0
# Longest wait for the final announcement to finish when nagging is disabled.
DRAIN_SECONDS = 15.0
# Announcements worth keeping when audio runs behind; older ones are stale.
MAX_QUEUED_ANNOUNCEMENTS = 2

RESERVED_TYPES = ("gap", "error")
RESERVED_KEYS = ("fired_at", "late_by")
# Every schedule string reaches stdout, and every stdout line lands in the
# agent's context. Generous for cook prose, small enough not to flood.
MAX_FIELD_CHARS = 4096

EXIT_OK = 0
EXIT_SCHEDULE = 1
EXIT_CRASH = 3

SCRIPT_DIR = Path(__file__).resolve().parent
AUDIO_MODES = ("tts", "chime", "silent")

_LABEL = "hold"
_SHUTTING_DOWN = False

# Cook messages carry degree signs and em-dashes; keep them literal where the
# stream can take it rather than shipping \u escapes to the agent.
for _stream in (sys.stdout, sys.stderr):
    if hasattr(_stream, "reconfigure"):
        try:
            _stream.reconfigure(encoding="utf-8", errors="backslashreplace")
        except (OSError, ValueError):
            pass


class ScheduleError(ValueError):
    """The schedule was missing, malformed, or empty."""


class Shutdown(Exception):
    """SIGTERM/SIGINT/SIGHUP — the cook acknowledged, or the agent is re-arming."""


def log(message):
    print(f"hold-timer[{_LABEL}]: {message}", file=sys.stderr, flush=True)


def emit(obj):
    """Write one flushed JSON line to stdout. Each line wakes the agent."""
    print(json.dumps(obj, separators=(",", ":"), ensure_ascii=False), flush=True)


def emit_error(message, detail, fatal):
    emit(
        {
            "type": "error",
            "message": message,
            "detail": detail,
            "fatal": fatal,
            "fired_at": int(time.time()),
        }
    )
    log(f"{'fatal' if fatal else 'degraded'}: {message}")


def fmt_duration(seconds):
    seconds = int(round(abs(seconds)))
    if seconds < 60:
        return f"{seconds}s"
    minutes, rest = divmod(seconds, 60)
    if minutes < 60:
        return f"{minutes} min" if rest == 0 else f"{minutes} min {rest}s"
    hours, minutes = divmod(minutes, 60)
    return f"{hours} h" if minutes == 0 else f"{hours} h {minutes} min"


