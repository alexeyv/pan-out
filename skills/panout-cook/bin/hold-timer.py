# Schedule
# ---------------------------------------------------------------------------

class Event:
    __slots__ = ("payload", "after", "target")

    def __init__(self, payload, after):
        self.payload = payload
        self.after = after
        self.target = 0.0  # wall-clock instant, set when the timer is armed


def parse_schedule(raw):
    """Parse schedule JSON (file path or literal) into Events sorted by time."""
    text = raw.strip()
    if not text:
        raise ScheduleError("schedule argument is empty")

    if text[0] not in "{[":
        try:
            text = Path(text).read_text(encoding="utf-8").strip()
        except OSError as exc:
            raise ScheduleError(f"cannot read schedule file '{raw}': {exc}")
        if not text:
            raise ScheduleError(f"schedule file '{raw}' is empty")

    try:
        data = json.loads(text)
    except json.JSONDecodeError as exc:
        raise ScheduleError(f"schedule is not valid JSON: {exc}")

    if not isinstance(data, dict):
        raise ScheduleError("schedule must be a JSON object")

    version = data.get("version")
    if isinstance(version, bool) or not isinstance(version, int) or version != 1:
        raise ScheduleError(
            f"unsupported schedule version {version!r} (expected integer 1)"
        )

    raw_events = data.get("events")
    if not isinstance(raw_events, list) or not raw_events:
        raise ScheduleError("schedule has no events")

    events = [parse_event(index, item) for index, item in enumerate(raw_events)]
    events.sort(key=lambda e: e.after)
    return events


def parse_event(index, item):
    if not isinstance(item, dict):
        raise ScheduleError(f"event {index} is not a JSON object")

    after = item.get("after")
    if isinstance(after, bool) or not isinstance(after, (int, float)):
        raise ScheduleError(
            f"event {index} needs a numeric 'after' (seconds from start)"
        )
    if not math.isfinite(after):
        # NaN compares false against everything, so it would arm a timer that
        # never fires and never nags.
        raise ScheduleError(f"event {index} has a non-finite 'after': {after}")
    if after < 0:
        raise ScheduleError(f"event {index} has a negative 'after': {after}")

    payload = dict(item)
    for field in ("type", "message"):
        value = payload.get(field)
        if not isinstance(value, str) or not value.strip():
            raise ScheduleError(f"event {index} needs a non-empty '{field}'")

    # Unknown keys pass through to stdout too, so cap every string, not just
    # the ones this script reads.
    for field, value in payload.items():
        if isinstance(value, str) and len(value) > MAX_FIELD_CHARS:
            raise ScheduleError(
                f"event {index} field '{field}' is {len(value)} characters — "
                f"the limit is {MAX_FIELD_CHARS}"
            )

    if payload["type"].strip().lower() in RESERVED_TYPES:
        raise ScheduleError(
            f"event {index} uses reserved type '{payload['type']}' — "
            "'gap' and 'error' are the timer's own"
        )

    for field in ("detail", "speak"):
        if field in payload:
            if not isinstance(payload[field], str):
                raise ScheduleError(f"event {index} has a non-string '{field}'")
            if not payload[field].strip():
                raise ScheduleError(f"event {index} has an empty '{field}'")

    for key in RESERVED_KEYS:
        if key in payload:
            log(f"event {index}: dropped caller-supplied '{key}' — the timer sets it")
            del payload[key]

    payload.setdefault("speak", payload["message"])
    return Event(payload, float(after))


