def _shutdown_handler(signum, _frame):
    global _SHUTTING_DOWN
    if _SHUTTING_DOWN:
        # Already cleaning up — a second signal must not raise through it.
        return
    _SHUTTING_DOWN = True
    raise Shutdown(signum)


def install_handlers():
    for name in ("SIGTERM", "SIGINT", "SIGHUP"):
        sig = getattr(signal, name, None)
        if sig is None:
            continue
        try:
            signal.signal(sig, _shutdown_handler)
        except (OSError, ValueError):
            log(f"cannot handle {name} — audio may outlive the timer")


def parse_args(argv):
    parser = argparse.ArgumentParser(
        prog="hold-timer.py",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "schedule", help="path to a schedule JSON file, or the schedule JSON itself"
    )
    parser.add_argument(
        "--label", default="hold", help="name of the hold, used in stderr logs"
    )
    parser.add_argument(
        "--tick-seconds",
        type=float,
        default=60.0,
        metavar="N",
        help="heartbeat tick interval, 0 to disable (default: 60)",
    )
    parser.add_argument(
        "--nag-seconds",
        type=float,
        default=45.0,
        metavar="N",
        help="completion alarm interval, 0 to disable and exit instead (default: 45)",
    )
    parser.add_argument(
        "--audio-mode",
        choices=AUDIO_MODES,
        default="tts",
        help="how to make noise (default: tts)",
    )
    args = parser.parse_args(argv)
    for name, value in (
        ("--tick-seconds", args.tick_seconds),
        ("--nag-seconds", args.nag_seconds),
    ):
        if not math.isfinite(value) or value < 0:
            parser.error(f"{name} must be a finite, non-negative number")
        if 0 < value < 1:
            # Sub-second cadences buy nothing in a kitchen and spin the loop.
            parser.error(f"{name} must be 0 (disabled) or at least 1")
    return args


def main(argv=None):
    global _LABEL
    args = parse_args(argv)
    _LABEL = args.label
    install_handlers()

    audio = None
    try:
        events = parse_schedule(args.schedule)
        audio = Audio(args.audio_mode)
        problem = audio.preflight()
        if problem:
            audio.failure_reported = True
            emit_error(
                f"Timer audio unavailable: {problem}",
                (
                    "The hold timer will count and send events, but the cook will hear "
                    "nothing from it — no ticks, no spoken announcements, no completion "
                    "alarm. Tell them, and voice every event yourself."
                ),
                fatal=False,
            )
        return run(events, audio, args.tick_seconds, args.nag_seconds)
    except ScheduleError as exc:
        emit_error(
            f"Timer could not start: {exc}",
            (
                "hold-timer.py rejected its schedule and exited. No events will fire. "
                "Tell the cook, then fall back to the manual timer mode for the rest of "
                "this hold."
            ),
            fatal=True,
        )
        return EXIT_SCHEDULE
    except Shutdown:
        log("stopped")
        return EXIT_OK
    except Exception as exc:  # noqa: BLE001 — a crash must still wake the agent
        emit_error(
            f"Timer crashed: {exc}",
            (
                "hold-timer.py died mid-hold, so no further events will fire. Tell the "
                "cook, work out how much hold time is left from the state file, and "
                "fall back to the manual timer."
            ),
            fatal=True,
        )
        log(f"crashed: {exc!r}")
        return EXIT_CRASH
    finally:
        if audio is not None:
            try:
                audio.shutdown()
            except Exception as exc:  # noqa: BLE001 — cleanup must not mask the exit
                log(f"audio cleanup failed: {exc!r}")


if __name__ == "__main__":
    sys.exit(main())
